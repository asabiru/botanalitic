export function buildUserPrompt(
  instrument: InstrumentCategory,
  ticker?: string,
  investorProfile?: string
): string {
  const tickerLine = ticker
    ? `Тикер клиента: ${ticker}`
    : "Конкретный тикер не указан — дай общий обзор по категории.";
  const profileLine = investorProfile
    ? `Профиль клиента: ${investorProfile}`
    : "Профиль клиента: не указан.";

  return `Категория: ${instrument.title}
${instrument.promptHint}
${tickerLine}
${profileLine}

Сформируй ответ строго по следующей структуре:

1. <b>Обзор рынка</b> — краткий обзор текущей ситуации (3-5 предложений)

2. <b>Ключевые уровни</b> — важные уровни поддержки и сопротивления

3. <b>Сценарии</b>
   • <b>Позитивный:</b> описание позитивного сценария
   • <b>Нейтральный:</b> описание нейтрального сценария
   • <b>Негативный:</b> описание негативного сценария

4. <b>Риски</b> — ключевые риск-факторы

5. <b>Идея для клиента</b> — конкретная идея с уровнями входа, стопа, целями и горизонтом

Каждую секцию начинай с заголовка в формате <b>N. Название</b>.
Ответ должен быть полезным, конкретным и профессиональным.`;
}

